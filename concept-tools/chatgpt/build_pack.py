def game_cells(tables):
    cells = {}
    for m in re.finditer(r"tex=\{([^}]*)\} size=\{\(([0-9.]+), ([0-9.]+)", open(tables, encoding='utf-8').read()):
        for name in re.findall(r"'([^']+)'", m.group(1)):
            cells.setdefault(name, int(float(m.group(2))))
    return cells


def game_art(src, out_dir, written, left):
    sheets_dir = os.path.join(src, 'sheets')
    tables = os.path.join(src, 'animation_tables.txt')
    cells = game_cells(tables) if os.path.exists(tables) else {}
    names = sorted(f for f in os.listdir(sheets_dir) if f.endswith('.png'))
    for stem, budget, wanted in GAME_GROUPS:
        items = []
        for name in wanted:
            path = os.path.join(sheets_dir, name + '.png')
            if not os.path.exists(path):
                print('game art: no', name)
                continue
            im = Image.open(path).convert('RGBA')
            cell = cells.get(name.rstrip(' 1'), cells.get(name))
            if not cell or im.width % cell or im.height % cell:
                cell = 32 if im.width % 32 == 0 and im.height % 32 == 0 and im.height >= 64 else None
            label = '%s  %dx%d%s' % (name, im.width, im.height, ', cell %d' % cell if cell else '')
            items.append((name, render(label, im, cell)))
        left += save_pages(out_dir, stem, items, written, budget)
    zp = os.path.join(out_dir, '05_game_sheets.zip')
    with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
        for f in names:
            z.write(os.path.join(sheets_dir, f), 'game_sheets/' + f)
        if os.path.exists(tables):
            z.write(tables, 'game_sheets/animation_tables.txt')
    written.append('05_game_sheets.zip')


def pack_order(s):
    kinds = {t['kind'] for r in s['rows'] for t in r['tags']}
    return (0 if s['folder'] == 'Vessel' and kinds & {'idle', 'move'} else 1 if 'attack' in kinds and
            s['folder'] == 'Vessel' else 2 if s['folder'] == 'Unit' else 3, s['name'])


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    out_dir = os.path.realpath(argv[1])
    repo = os.path.realpath(REPO)
    if out_dir == repo or out_dir.startswith(repo + os.sep):
        sys.exit('write the pack outside the repository: it can hold the game\'s sprites')
    opt = lambda k: argv[argv.index(k) + 1] if k in argv else None
    os.makedirs(out_dir, exist_ok=True)
    cache = opt('--cache') or os.path.join(out_dir, '_cache')
    ab = load_artbench()
    sheets = []
    for part in ab.VESSELS:
        sheets += ab.vessel_sheets(part, cache)
    msheets, icons = ab.mode_sheets()
    sheets += msheets
    models = ab.models(cache, os.path.join(cache, 'models_out'))
    commit = os.popen('git -C %s rev-parse --short HEAD' % REPO).read().strip()
    looks = scope_looks()
    man = manifest(sheets, icons, models, looks, commit)
    if opt('--manifest'):
        open(opt('--manifest'), 'w', encoding='utf-8').write(man)
    written = []

    open(os.path.join(out_dir, '01_RogueWaves_Art_Guide.md'), 'w', encoding='utf-8').write(guide(man))
    shutil.copy(os.path.join(HERE, 'pixelize.py'), os.path.join(out_dir, '02_pixelize.py'))
    open(os.path.join(out_dir, '03_palettes.txt'), 'w', encoding='utf-8').write(palettes_txt(sheets, icons))
    written += ['01_RogueWaves_Art_Guide.md', '02_pixelize.py', '03_palettes.txt']
    with zipfile.ZipFile(os.path.join(out_dir, '04_pack_sheets.zip'), 'w', zipfile.ZIP_DEFLATED) as z:
        for s in sheets + icons:
            tmp = os.path.join(cache, 'png', s['part'], s['name'] + '.png')
            os.makedirs(os.path.dirname(tmp), exist_ok=True)
            to_image(s['w'], s['h'], s['_px']).save(tmp)
            z.write(tmp, 'pack_sheets/%s/%s.png' % (s['part'], s['name']))
    written.append('04_pack_sheets.zip')

    by, left = {}, []
    for s in sorted(sheets, key=pack_order):
        label = '%s  %dx%d, cell %d, now %s' % (s['name'], s['w'], s['h'], s['cell'], s['origin'])
        by.setdefault(s['part'], []).append((s['name'], render(label, to_image(s['w'], s['h'], s['_px']), s['cell'])))
    for part, items in by.items():
        left += save_pages(out_dir, 'pack_' + part.lower(), items, written, PACK_BUDGET.get(part, 1))
    left += save_pages(out_dir, 'pack_icons', [(i['name'], render(i['name'], to_image(i['w'], i['h'], i['_px']), None))
                                               for i in icons], written, 1)
    his = []
    for v in ('yossele', 'spool', 'uloe'):
        p = os.path.join(REPO, 'docs', 'concepts', 'art', v + '_8x.png')
        if os.path.exists(p):
            his.append((v, render("Dimitri's %s concept (8x)" % v.capitalize(), Image.open(p).convert('RGBA'), None)))
    if his:
        left += save_pages(out_dir, 'his_sprites', his, written, 1)
    if opt('--game-art'):
        game_art(opt('--game-art'), out_dir, written, left)

    readme = ['Rogue Waves art pack for the ChatGPT Project "Rogue Waves Art" (built at %s).' % commit, '',
              'PRIVATE: the game_* files and 05_game_sheets.zip are the base game\'s own sprites. Keep them in this',
              'Project only: never post them, never put them in the public repository.', '',
              'Upload every file below to the Project, and paste docs/art/PROJECT_INSTRUCTIONS.md into its instructions.', '']
    for f in written:
        readme.append('  ' + f)
    if left:
        readme += ['', 'Only in the zips (no room on the contact sheets): ' + ', '.join(left)]
    open(os.path.join(out_dir, '00_README.txt'), 'w', encoding='utf-8').write('\n'.join(readme) + '\n')
    print('pack: %d files in %s (%d sheets, %d icons, %d models in the manifest)' % (len(written) + 1, out_dir,
                                                                                    len(sheets), len(icons), len(models)))
    for f in ['00_README.txt'] + written:
        print('  %-34s %7d KB' % (f, os.path.getsize(os.path.join(out_dir, f)) // 1024))


if __name__ == '__main__':
    main(sys.argv)
