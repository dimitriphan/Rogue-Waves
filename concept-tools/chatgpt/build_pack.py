#!/usr/bin/env python3
"""Builds the ChatGPT art pack (docs/art/README.md): the files Dimitri uploads to his ChatGPT Project "Rogue Waves Art",
and the public asset manifest. Run once cloud-check is set up (TDS_Mod/Tools/cloud-check/setup.sh):

    python3 concept-tools/chatgpt/build_pack.py <out_dir> [--game-art DIR] [--manifest docs/art/ASSET_MANIFEST.md]

<out_dir> must be OUTSIDE the repository (it holds the game's sprites when --game-art is given; CLAUDE.md "Rules").
--game-art is the folder of base-game sheets read from the game (art_dump_2026-10-15/, with sheets/ and
animation_tables.txt); without it the pack has only the mod's own art. --manifest rewrites the public manifest.

The pack (one ChatGPT Project holds 25 files on Plus):
  00_README.txt               what each file is, and that the game_* files are private
  01_RogueWaves_Art_Guide.md  docs/art/CHATGPT_BRIEF.md + the style rules + the asset manifest, in one file
  02_pixelize.py              the clean-up and check script ChatGPT runs on its own pictures
  03_palettes.txt             every palette, by section name, for pixelize.py --palette palettes.txt:<section>
  04_pack_sheets.zip          every pack sheet and icon at game size, under its file name
  05_game_sheets.zip          every base-game sheet at game size (private; only with --game-art)
  pack_*.png, game_*.png, his_sprites.png   labelled contact sheets, sized so the picture is not shrunk on upload
"""
