PAGE_W, PAGE_H = 768, 2040      # ChatGPT shrinks a picture to fit 2048 and then its short side to 768
BG, CELL_BG, INK = (200, 206, 211), (216, 221, 225), (46, 74, 98)
FONT = ImageFont.load_default(size=13)


def load_artbench():
    spec = importlib.util.spec_from_file_location('artbench_build', os.path.join(REPO, 'TDS_Mod', 'Tools', 'artbench',
                                                                                  'build.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def to_image(w, h, rgba):
    return Image.frombytes('RGBA', (w, h), bytes(rgba))


# ------------------------------------------------------------------ scope Look lines

def norm(s):
    return re.sub(r'[^a-z0-9]', '', s.lower())


def scope_looks():
    """{normalised item name: (scope file, item name, Look line)} from every {Item} ... - Look: line in docs/scope."""
    out = {}
    d = os.path.join(REPO, 'docs', 'scope')
    for f in sorted(os.listdir(d)):
        item = None
        for ln in open(os.path.join(d, f), encoding='utf-8', errors='replace'):
            m = re.match(r'\s*\{([^}]+)\}\s*$', ln)
            if m:
                item = m.group(1).strip()
            m = re.match(r'\s*-\s*Look:\s*(.+)', ln)
            if m and item:
                out[norm(item)] = (f, item, m.group(1).strip())
    return out


def drawn_looks():
    """{icon file name: (generator, 'Item: what it shows')} from the comment on each icon in the temporary-art scripts."""
    out, d = {}, os.path.join(REPO, 'concept-tools', 'temp_art')
    for f in sorted(os.listdir(d)):
        if f.endswith('.py'):
            for m in re.finditer(r"'((?:Direction|Cardinal|RogueWaves)_\w+)':\s*\[\s*#\s*(.+)", open(os.path.join(d, f)).read()):
                out.setdefault(m.group(1), ('concept-tools/temp_art/' + f, m.group(2).strip()))
    return out


def icon_look(name, looks, drawn):
    key = norm(name.split('_', 1)[1] if '_' in name else name)
    for k, v in looks.items():
        if k == key or k.replace('the', '') == key:
            return '%s (`%s`)' % (v[2], v[0])
    if name in drawn:
        return '%s (as drawn, `%s`)' % (drawn[name][1], drawn[name][0])
    near = [v for k, v in looks.items() if len(key) >= 4 and k.startswith(key)]
    return '%s (`%s`, %s)' % (near[0][2], near[0][0], near[0][1]) if len(near) == 1 else ''


# ------------------------------------------------------------------ manifest

def manifest(sheets, icons, models, looks, commit):
    drawn = drawn_looks()
    L = ['# Rogue Waves asset manifest', '',
         'Generated by `concept-tools/chatgpt/build_pack.py` from the Art Bench data (`TDS_Mod/Tools/artbench/build.py`) '
         'at `%s`; do not edit by hand, rebuild. Every sprite sheet, icon and model the pack ships, with what a new '
         'picture must match to replace it: the file name, the size, the cell and what each row of cells holds. '
         'How a file comes back in: `docs/art/README.md`.' % commit, '',
         '**Reading a sheet.** Cells are square and read left to right; a row holds one facing of one or more '
         'animations (`idle_v0 + move_v0` = 6 idle frames then 6 move frames, facing v0). Facings: v0 toward the '
         'camera heading right, v1 toward heading left, v2 away heading right, v3 away heading left (kit `docs/18` '
         '§1); "mirror of" means the code draws that facing as a flip, so only the source needs drawing. "Now" is '
         'what the build uses today: `code` (drawn by the builder), `temporary` or `final` (a file).', '']
    by_part = {}
    for s in sheets:
        by_part.setdefault(s['part'], []).append(s)
    L += ['## Sprite sheets (%d)' % len(sheets), '']
    for part, items in by_part.items():
        L += ['### %s' % part, '', '| Sheet (file name) | Size | Cell | Kind | Rows: animation (frames) | Now |',
              '| --- | --- | --- | --- | --- | --- |']
        for s in items:
            rows = []
            for i, r in enumerate(s['rows']):
                tags = ', '.join('%s (%d%s)' % (t['name'], t['count'],
                                                '; mirror of ' + t['mirrorOf'] if t.get('mirrorOf') else '')
                                 for t in r['tags'])
                rows.append('%d: %s' % (i, tags))
            L.append('| `%s.png` | %d×%d | %d | %s | %s | %s |' % (s['name'], s['w'], s['h'], s['cell'], s['folder'],
                                                                   '<br>'.join(rows), s['origin']))
        L.append('')
    L += ['## Icons (%d)' % len(icons), '',
          'Each icon is one opaque object on a clear ground, readable at 1× (kit `docs/03` §2, `docs/STYLE.md` '
          '"Motifs"). The Look is the scope\'s line for it, else what the temporary icon was drawn as.', '',
          '| Icon (file name) | Size | Kind | Look (scope) |', '| --- | --- | --- | --- |']
    for i in icons:
        look = icon_look(i['name'], looks, drawn)
        L.append('| `%s.png` | %d×%d | %s | %s |' % (i['name'], i['w'], i['h'], i['kind'], look.replace('|', '/')))
    L += ['', '## Models (%d): towers, buildings, objects, projectiles' % len(models), '',
          'Towers and buildings are low-poly 3D models built in code (kit `docs/03` §4: low-poly sleek, never voxel; '
          'every tower shows its vessel\'s motif, `docs/STYLE.md` "Towers"). A picture can only be a concept for '
          'one: front and three-quarter views on a plain ground, the vessel\'s palette, the silhouette and the one '
          'feature each upgrade adds. Claude turns a picked concept into the model.', '',
          '| Part | Model | Group | Triangles |', '| --- | --- | --- | --- |']
    for m in models:
        L.append('| %s | %s | %s | %d |' % (m['part'], m['name'], m['group'], m['tris']))
    L += ['', '## Not pictures', '',
          'Sounds (kit `docs/03` §6) and effects drawn by code at run time (the foes\' modifier rings, the sea chart, '
          'number digits) are not made from pictures.', '']
    return '\n'.join(L)


# ------------------------------------------------------------------ the guide

def section(path, start, stop=None):
    """Lines from the heading that starts with `start` up to (not including) the heading that starts with `stop`."""
    lines, out, on = open(path, encoding='utf-8').read().splitlines(), [], False
    for ln in lines:
        if ln.startswith('#') and ln.lstrip('#').strip().startswith(start):
            on = True
        elif on and stop and ln.startswith('#') and ln.lstrip('#').strip().startswith(stop):
            break
        if on:
            out.append(ln)
    if not out:
        sys.exit('section %r not found in %s' % (start, path))
    return '\n'.join(out)


def guide(manifest_md):
    parts = [open(os.path.join(REPO, 'docs', 'art', 'CHATGPT_BRIEF.md'), encoding='utf-8').read(),
             '\n---\n\n# Part 2. The pack\'s style sheet (`docs/STYLE.md`)\n',
             open(os.path.join(REPO, 'docs', 'STYLE.md'), encoding='utf-8').read().split('\n## Art review')[0],
             '\n---\n\n# Part 3. How the game\'s own characters are drawn (kit `docs/18`, measured from the game)\n',
             section(os.path.join(KIT, 'docs', '18_CHARACTER_ART.md'), '1. How the game', '8. Corrections'),
             '\n---\n\n# Part 4. Sprites, UI art and effects (kit `docs/03` §1, §2, §5)\n',
             section(os.path.join(KIT, 'docs', '03_ART_AND_AUDIO.md'), '1. The vessel sprite', '3. Units'),
             section(os.path.join(KIT, 'docs', '03_ART_AND_AUDIO.md'), '5. Effects', '6. Sound'),
             '\n---\n\n# Part 5. Dimitri\'s own vessel concepts (`docs/concepts/YOSSELE_SPOOL_ULOE.md`)\n',
             open(os.path.join(REPO, 'docs', 'concepts', 'YOSSELE_SPOOL_ULOE.md'), encoding='utf-8').read(),
             '\n---\n\n# Part 6. Every asset in the pack\n', manifest_md.split('\n', 1)[1]]
    return '\n'.join(parts)


# ------------------------------------------------------------------ palettes

def hexes(px):
    return sorted({'%02X%02X%02X' % tuple(px[i:i + 3]) for i in range(0, len(px), 4) if px[i + 3]})


def palettes_txt(sheets, icons):
    L = ['# Palettes for pixelize.py --palette 03_palettes.txt:<section>. A section is every colour that set uses.', '']
    for f in ('tds_base_vessels', 'tds_foes', 'tds_shared'):
        L.append('[%s]' % f.replace('tds_', '').replace('base_vessels', 'base_vessels'))
        for ln in open(os.path.join(KIT, 'reference', 'palettes', f + '.gpl'), encoding='utf-8'):
            p = ln.split()
            if len(p) >= 3 and all(v.isdigit() for v in p[:3]):
                L.append('%02X%02X%02X %s' % (int(p[0]), int(p[1]), int(p[2]), ' '.join(p[3:])))
        L.append('')
    L.append('[pack_ui]')
    for ln in open(os.path.join(REPO, 'docs', 'STYLE.md'), encoding='utf-8'):
        for h in re.findall(r'`([0-9A-F]{6})`', ln.split('## Motifs')[0]):
            L.append(h)
        if ln.startswith('## Motifs'):
            break
    L.append('')
    by = {}
    for s in sheets:
        by.setdefault(s['part'].lower(), set()).update(hexes(s['_px']))
    for part, cols in by.items():
        L += ['[%s]' % part] + sorted(cols) + ['']
    L += ['[pack_icons]'] + sorted({h for i in icons for h in hexes(i['_px'])}) + ['']
    return '\n'.join(L)


# ------------------------------------------------------------------ contact sheets

CELL_TONES = ((214, 219, 223), (228, 232, 235))   # a checkerboard shows each cell without gaps


def render(label, im, cell):
    """One item: its label over its cells, the cells on a checkerboard, scaled so a cell shows about 64 px wide."""
    w, h = im.size
    cw = cell or max(w, h)
    scale = max(1, min(5, 64 // cw)) if cell else max(1, min(4, 256 // cw))
    while scale > 1 and (w * scale > PAGE_W or h * scale + 18 > PAGE_H):
        scale -= 1
    out = Image.new('RGB', (min(PAGE_W, max(w * scale, FONT.getbbox(label)[2] + 4)), h * scale + 18), BG)
    d = ImageDraw.Draw(out)
    d.text((2, 2), label, fill=INK, font=FONT)
    if cell:
        for r in range(h // cell):
            for c in range(w // cell):
                d.rectangle([c * cell * scale, 18 + r * cell * scale, (c + 1) * cell * scale - 1,
                             18 + (r + 1) * cell * scale - 1], fill=CELL_TONES[(r + c) % 2])
    else:
        d.rectangle([0, 18, w * scale - 1, 18 + h * scale - 1], fill=CELL_TONES[0])
    big = im.resize((w * scale, h * scale), Image.NEAREST)
    out.paste(big, (0, 18), big)
    return out


def pages(items):
    """Shelf-pack rendered items onto pages 768 wide and at most 2040 tall."""
    out, page, x, y, shelf = [], None, 0, 0, 0
    for it in items:
        if page is not None and x + it.width > PAGE_W:
            x, y, shelf = 0, y + shelf + 4, 0
        if page is None or y + it.height > PAGE_H:
            if page:
                out.append(page.crop((0, 0, PAGE_W, y + shelf if y + shelf <= PAGE_H else y)))
            page, x, y, shelf = Image.new('RGB', (PAGE_W, PAGE_H), BG), 0, 0, 0
        page.paste(it, (x, y))
        x, shelf = x + it.width + 4, max(shelf, it.height)
    if page:
        out.append(page.crop((0, 0, PAGE_W, y + shelf)))
    return out


def save_pages(out_dir, stem, items, written, budget):
    """Writes at most `budget` pages; returns the labels of the items left out (they are still in the zips)."""
    ps, kept, left = [], [], []
    for label, im in items:
        trial = pages([r for _, r in kept] + [im])
        if len(trial) <= budget:
            kept.append((label, im))
            ps = trial
        else:
            left.append(label)
    for i, p in enumerate(ps):
        name = '%s%s.png' % (stem, '' if len(ps) == 1 else '_%d' % (i + 1))
        p.save(os.path.join(out_dir, name))
        written.append(name)
    return left


